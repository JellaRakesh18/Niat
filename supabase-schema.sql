-- 1. EXTENSIONS
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";
CREATE EXTENSION IF NOT EXISTS "pgcrypto";

-- ==============================================================================
-- 2. TABLE DEFINITIONS
-- ==============================================================================

-- 2.1 JOBS TABLE (Active Job Openings Across India)
CREATE TABLE IF NOT EXISTS public.jobs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    trade TEXT NOT NULL,
    employer TEXT NOT NULL,
    employer_phone TEXT DEFAULT '9876543210',
    phone TEXT DEFAULT '9876543210',
    wage INTEGER NOT NULL CHECK (wage >= 300),
    workers_needed INTEGER DEFAULT 1,
    hours TEXT DEFAULT '8 hours',
    state TEXT NOT NULL,
    district TEXT NOT NULL,
    city TEXT NOT NULL,
    description TEXT,
    posted_date TEXT DEFAULT CURRENT_DATE::text,
    is_scam BOOLEAN DEFAULT false,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 2.2 WORKERS DIRECTORY TABLE
CREATE TABLE IF NOT EXISTS public.workers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    phone TEXT NOT NULL,
    trade TEXT NOT NULL,
    wage INTEGER NOT NULL CHECK (wage >= 300),
    experience INTEGER DEFAULT 1,
    status TEXT DEFAULT 'Available',
    state TEXT NOT NULL,
    district TEXT NOT NULL,
    city TEXT NOT NULL,
    verified BOOLEAN DEFAULT true,
    photo_skill_verified BOOLEAN DEFAULT true,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 2.3 APPLICATIONS TABLE (Job Applications from Workers)
CREATE TABLE IF NOT EXISTS public.applications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_id BIGINT,
    job_title TEXT,
    worker_name TEXT NOT NULL,
    worker_phone TEXT NOT NULL,
    worker_trade TEXT NOT NULL,
    status TEXT DEFAULT 'Submitted',
    applied_date TEXT DEFAULT CURRENT_DATE::text,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 2.4 ATTENDANCE LOGS TABLE (Facial / Geotagged Check-ins)
CREATE TABLE IF NOT EXISTS public.attendance (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    worker_name TEXT NOT NULL,
    date TEXT NOT NULL,
    timestamp TEXT NOT NULL,
    type TEXT DEFAULT 'Check-In',
    location TEXT,
    verified BOOLEAN DEFAULT true,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 2.5 INCIDENTS / SAFETY INJURY LOGS TABLE
CREATE TABLE IF NOT EXISTS public.incidents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    worker_name TEXT NOT NULL,
    incident_type TEXT NOT NULL,
    severity TEXT NOT NULL,
    contractor_phone TEXT,
    location TEXT NOT NULL,
    description TEXT,
    timestamp TEXT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

