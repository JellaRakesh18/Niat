CREATE POLICY "Allow public read access on workers" ON public.workers FOR SELECT USING (true);
CREATE POLICY "Allow public insert on workers" ON public.workers FOR INSERT WITH CHECK (true);
CREATE POLICY "Allow public update on workers" ON public.workers FOR UPDATE USING (true);

CREATE POLICY "Allow public read access on applications" ON public.applications FOR SELECT USING (true);
CREATE POLICY "Allow public insert on applications" ON public.applications FOR INSERT WITH CHECK (true);

CREATE POLICY "Allow public read access on attendance" ON public.attendance FOR SELECT USING (true);
CREATE POLICY "Allow public insert on attendance" ON public.attendance FOR INSERT WITH CHECK (true);

CREATE POLICY "Allow public read access on incidents" ON public.incidents FOR SELECT USING (true);
CREATE POLICY "Allow public insert on incidents" ON public.incidents FOR INSERT WITH CHECK (true);

-- Enable Realtime publication
ALTER PUBLICATION supabase_realtime ADD TABLE public.jobs;
